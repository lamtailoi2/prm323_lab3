import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../models/internship_application.dart';
import '../../theme/app_colors.dart';
import 'display_format.dart';

/// File name of an exported report: `application-report-2026-11-12.pdf`.
///
/// One report per day is enough for the demo, and a date in the name keeps
/// the Storage object recognisable in the Firebase console (G-05).
String reportFileName(DateTime generatedAt) {
  final local = generatedAt.toLocal();
  final month = local.month.toString().padLeft(2, '0');
  final day = local.day.toString().padLeft(2, '0');
  return 'application-report-${local.year}-$month-$day.pdf';
}

/// Builds the `Application report` PDF from the student's own applications
/// (Lab 3 "export and upload", G-05).
///
/// Pure on purpose: no Firebase or Flutter widget access, so it is unit
/// testable and the service only uploads the bytes and writes the metadata.
/// [baseFont] / [boldFont] are passed by the service, because the built-in
/// PDF fonts cannot render Vietnamese names; without them the default
/// Helvetica is used (ASCII test data).
Future<Uint8List> buildApplicationReportPdf({
  required List<InternshipApplication> applications,
  required String studentName,
  required DateTime generatedAt,
  pw.Font? baseFont,
  pw.Font? boldFont,
}) async {
  if (applications.isEmpty) {
    throw ArgumentError.value(
      applications,
      'applications',
      'the report needs at least one application',
    );
  }

  final textPrimary = PdfColor.fromInt(AppColors.textPrimary.toARGB32());
  final textSecondary = PdfColor.fromInt(AppColors.textSecondary.toARGB32());
  final primary = PdfColor.fromInt(AppColors.primary.toARGB32());
  final surfaceVariant = PdfColor.fromInt(AppColors.surfaceVariant.toARGB32());
  final border = PdfColor.fromInt(AppColors.border.toARGB32());

  final theme = baseFont != null && boldFont != null
      ? pw.ThemeData.withFont(base: baseFont, bold: boldFont)
      : null;
  final document = pw.Document(theme: theme);

  // Newest first, like My Applications.
  final ordered = <InternshipApplication>[...applications]
    ..sort((a, b) {
      final byDate = b.appliedAt.compareTo(a.appliedAt);
      return byDate != 0 ? byDate : a.title.compareTo(b.title);
    });

  final counts = <ApplicationStatus, int>{};
  for (final application in ordered) {
    counts.update(application.status, (value) => value + 1, ifAbsent: () => 1);
  }

  // The column only exists when at least one row has a date to show.
  final showNextStep = ordered.any(
    (application) => application.nextStepAt != null,
  );
  final headers = <String>[
    'Position',
    'Company',
    'Applied',
    'Status',
    if (showNextStep) 'Next step',
  ];
  final rows = <List<String>>[
    for (final application in ordered)
      <String>[
        application.title,
        application.companyName,
        formatShortDate(application.appliedAt),
        application.status.label,
        if (showNextStep)
          application.nextStepAt == null
              ? '-'
              : formatShortDate(application.nextStepAt!),
      ],
  ];

  document.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(32, 28, 32, 28),
      maxPages: 200,
      header: (context) => pw.Container(
        alignment: pw.Alignment.centerRight,
        margin: const pw.EdgeInsets.only(bottom: 12),
        child: pw.Text(
          'Application report',
          style: pw.TextStyle(fontSize: 9, color: textSecondary),
        ),
      ),
      footer: (context) => pw.Container(
        alignment: pw.Alignment.centerLeft,
        margin: const pw.EdgeInsets.only(top: 12),
        child: pw.Text(
          'Generated by Internly on ${formatShortDate(generatedAt)}'
          '  ·  Page ${context.pageNumber} of ${context.pagesCount}',
          style: pw.TextStyle(fontSize: 8, color: textSecondary),
        ),
      ),
      build: (context) => [
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          crossAxisAlignment: pw.CrossAxisAlignment.end,
          children: [
            pw.Text(
              'Internly.',
              style: pw.TextStyle(
                fontSize: 16,
                fontWeight: pw.FontWeight.bold,
                color: primary,
              ),
            ),
          ],
        ),
        pw.SizedBox(height: 16),
        pw.Text(
          'Application report',
          style: pw.TextStyle(
            fontSize: 22,
            fontWeight: pw.FontWeight.bold,
            color: textPrimary,
          ),
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          studentName,
          style: pw.TextStyle(fontSize: 11, color: textPrimary),
        ),
        pw.SizedBox(height: 2),
        pw.Text(
          'Generated ${formatShortDate(generatedAt)}',
          style: pw.TextStyle(fontSize: 9, color: textSecondary),
        ),
        pw.SizedBox(height: 16),
        pw.Container(
          width: double.infinity,
          padding: const pw.EdgeInsets.all(12),
          decoration: pw.BoxDecoration(
            color: surfaceVariant,
            borderRadius: pw.BorderRadius.circular(8),
          ),
          child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text(
                ordered.length == 1
                    ? '1 application'
                    : '${ordered.length} applications',
                style: pw.TextStyle(
                  fontSize: 11,
                  fontWeight: pw.FontWeight.bold,
                  color: textPrimary,
                ),
              ),
              pw.SizedBox(height: 6),
              pw.Wrap(
                spacing: 14,
                runSpacing: 4,
                children: [
                  for (final status in ApplicationStatus.values)
                    if (counts[status] case final count?)
                      pw.Text(
                        '${status.label}: $count',
                        style: pw.TextStyle(fontSize: 9, color: textSecondary),
                      ),
                ],
              ),
            ],
          ),
        ),
        pw.SizedBox(height: 18),
        pw.TableHelper.fromTextArray(
          headers: headers,
          data: rows,
          border: pw.TableBorder(
            horizontalInside: pw.BorderSide(color: border, width: 0.5),
            bottom: pw.BorderSide(color: border, width: 0.5),
          ),
          headerStyle: pw.TextStyle(
            fontSize: 8.5,
            fontWeight: pw.FontWeight.bold,
            color: textSecondary,
          ),
          cellStyle: pw.TextStyle(fontSize: 8.5, color: textPrimary),
          headerAlignment: pw.Alignment.centerLeft,
          cellAlignment: pw.Alignment.centerLeft,
          cellPadding: const pw.EdgeInsets.symmetric(
            vertical: 5,
            horizontal: 3,
          ),
          columnWidths: <int, pw.TableColumnWidth>{
            0: const pw.FlexColumnWidth(3),
            1: const pw.FlexColumnWidth(2.2),
            2: const pw.FlexColumnWidth(1.5),
            3: const pw.FlexColumnWidth(1.6),
            if (showNextStep) 4: const pw.FlexColumnWidth(1.6),
          },
        ),
      ],
    ),
  );

  return document.save();
}
